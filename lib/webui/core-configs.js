export function flattenCoreFields(fields) {
  const out = {}
  const walk = (node, prefix) => {
    if (!node || typeof node !== "object") return
    for (const [key, value] of Object.entries(node)) {
      if (!value || typeof value !== "object") continue
      const path = prefix ? `${prefix}.${key}` : key
      const meta = {}
      if (typeof value.label === "string") meta.label = value.label
      if (typeof value.description === "string") meta.description = value.description
      if (Array.isArray(value.options)) meta.options = value.options
      if (value.allowEmpty === true) meta.allowEmpty = true
      if (meta.label || meta.description || meta.options || meta.allowEmpty) out[path] = meta
      walk(value, path)
    }
  }
  walk(fields, "")
  return out
}
